console.log(5 + 2);        // Operador de suma (+): suma números
console.log("Hola " + "Eder"); // Operador de concatenación (+): une textos

console.log(5 - 2);        // Operador de resta (-): resta valores numéricos
console.log(5 * 2);        // Operador de multiplicación (*): multiplica valores
console.log(5 / 2);        // Operador de división (/): divide valores

console.log(5 % 2);        // Operador módulo (%): devuelve el residuo de la división (5 ÷ 2 = 2, sobra 1)
console.log(10 % 3);       // Módulo (%): residuo de 10 ÷ 3 (sobra 1)
